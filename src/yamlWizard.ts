import * as vscode from 'vscode';

export function showYamlWizard(context: vscode.ExtensionContext) {
    const panel = vscode.window.createWebviewPanel(
        'yamlWizard',
        'NeuralForge Configuration Wizard (YOLO26 & Next-Gen)',
        vscode.ViewColumn.One,
        {
            enableScripts: true
        }
    );

    panel.webview.html = getWebviewContent();

    panel.webview.onDidReceiveMessage(
        message => {
            switch (message.command) {
                case 'generate':
                    const yamlContent = generateYamlFromData(message.data);
                    vscode.workspace.openTextDocument({ content: yamlContent, language: 'yaml' })
                        .then(doc => vscode.window.showTextDocument(doc));
                    return;
            }
        },
        undefined,
        context.subscriptions
    );
}

function generateYamlFromData(data: any): string {
    const task = data.task || 'detect';
    
    // Check if Ultra-Lite Minimal mode is requested
    if (data.yamlMode === 'lite') {
        const targetWorkerLine = data.targetWorker ? `\n  debug: "${data.targetWorker}"` : '';
        return `model: "${data.model || 'yolo26n.pt'}"
style: "${task}"

train:
  data: "${data.dataset || '/data/datasets/dataset.yaml'}"
  epochs: ${data.epochs || 100}
  imgsz: 640

sweeper:
  study_name: "${data.project || 'project'}_${data.datasetName || 'dataset'}"${targetWorkerLine}

metadata:
  content: "YOLO training study generated by NeuralForge VSCode Wizard (Ultra-Lite)"
  author: "User"
  documentation: "Minimal NeuralForge smart configuration"
`;
    }

    const tuneStr = data.tune ? 'true' : 'false';
    const batchSize = data.batchSize || 16;
    
    // Select correct fitness metric according to CV task
    let fitness = "metrics/mAP50-95(B)";
    if (task === 'segment') {
        fitness = "metrics/mAP50-95(M)";
    } else if (task === 'classify') {
        fitness = "metrics/accuracy_top1";
    } else if (task === 'pose') {
        fitness = "metrics/mAP50-95(P)";
    }

    const timeBlock = (data.time && Number(data.time) > 0) ? `\n  time: ${Number(data.time)}` : '';
    const targetWorkerBlock = data.targetWorker ? `\n  target_worker_queue: "${data.targetWorker}"\n  debug: "${data.targetWorker}"` : '';
    const startAtBlock = data.startAt ? `\nstart_at: "${data.startAt}"` : '';

    return `model: "${data.model || 'yolo26n.pt'}"
type: "yolo"${startAtBlock}
train:
  task: "${task}"
  data: "${data.dataset || '/data/datasets/dataset.yaml'}"
  epochs: ${data.epochs || 100}${timeBlock}
  batch: ${batchSize}
  imgsz: 640
post_train:
  xai: ${data.enableXai ? 'true' : 'false'}
  adversarial: ${data.enableAdversarial ? 'true' : 'false'}
  latex: ${data.enableLatex ? 'true' : 'false'}
sweeper:
  version: 2
  study_name: "${data.project || 'project'}_${data.datasetName || 'dataset'}"
  direction: "maximize"
  fitness: "${fitness}"
  algorithm: "optuna"
  sampler: "${data.sampler || 'tpe'}"
  tune: ${tuneStr}
  n_trials: ${data.nTrials || 3}${targetWorkerBlock}
  search_space:
    model: ["choice", "${data.model || 'yolo26n.pt'}"]
    train:
      imgsz: ["choice", 640]
      lr0: ["float", ${data.lrMin || 0.001}, ${data.lrMax || 0.01}]
      batch: ["choice", ${batchSize}]
metadata:
  content: "YOLO training study generated by NeuralForge VSCode Wizard"
  author: "User"
  documentation: "Auto-generated NeuralForge sweeper configuration"
`;
}

