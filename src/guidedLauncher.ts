import * as vscode from 'vscode';
import * as fs from 'fs';
import * as path from 'path';
import { ClusterApiClient } from './clusterApiClient';
import { LogStreamer } from './logStreamer';

export function openGuidedLauncher(context: vscode.ExtensionContext) {
    const panel = vscode.window.createWebviewPanel(
        'neuralforgeGuidedLaunch',
        '🚀 NeuralForge: Training Studio Hub',
        vscode.ViewColumn.One,
        {
            enableScripts: true,
            retainContextWhenHidden: true
        }
    );

    // Initial connection settings
    const config = vscode.workspace.getConfiguration('neuralforge');
    const initialSettings = {
        controlHost: config.get<string>('controlHost', '192.168.10.252'),
        controlPort: config.get<number>('controlPort', 23442),
        sambaHost: context.globalState.get<string>('neuralforge.sambaHost', '192.168.10.250'),
        sambaUser: context.globalState.get<string>('neuralforge.sambaUser', 'cifs_worker'),
        sambaPass: context.globalState.get<string>('neuralforge.sambaPass', '')
    };

    panel.webview.html = getGuidedLauncherHtml(initialSettings);

    panel.webview.onDidReceiveMessage(async (message) => {
        if (message.command === 'saveSettings') {
            const { controlHost, controlPort, sambaHost, sambaUser, sambaPass } = message.payload;
            try {
                await config.update('controlHost', controlHost, vscode.ConfigurationTarget.Global);
                await config.update('controlPort', Number(controlPort), vscode.ConfigurationTarget.Global);
                await context.globalState.update('neuralforge.sambaHost', sambaHost);
                await context.globalState.update('neuralforge.sambaUser', sambaUser);
                await context.globalState.update('neuralforge.sambaPass', sambaPass);
                panel.webview.postMessage({
                    command: 'settingsSaved',
                    message: '✅ Connection & Samba credentials saved successfully.'
                });
                vscode.window.showInformationMessage('NeuralForge cluster & storage settings saved.');
            } catch (err: any) {
                panel.webview.postMessage({
                    command: 'error',
                    message: `Failed to save settings: ${err.message}`
                });
            }
            return;
        }

        if (message.command === 'generateYamlOnly' || message.command === 'submitTraining') {
            const { 
                dataset, 
                task, 
                model, 
                studyName, 
                description, 
                epochs, 
                batchSize, 
                xaiEnabled, 
                targetQueue, 
                isSweeper, 
                sweeperTrials, 
                sweeperSampler, 
                sweeperMetric 
            } = message.payload;

            const workspaceFolders = vscode.workspace.workspaceFolders;
            const targetFolder = workspaceFolders && workspaceFolders.length > 0
                ? workspaceFolders[0].uri.fsPath
                : process.cwd();

            const sanitizedStudy = (studyName || `study_${task}_${Date.now().toString(36)}`)
                .replace(/[^a-zA-Z0-9_-]/g, '_');
            const configFileName = `neuralforge_${sanitizedStudy}.yaml`;
            const configFilePath = path.join(targetFolder, configFileName);

            let sweeperBlock = '';
            if (isSweeper) {
                sweeperBlock = `
sweeper:
  trials: ${sweeperTrials || 10}
  sampler: "${sweeperSampler || 'tpe'}"
  metric: "${sweeperMetric || (task === 'classify' ? 'metrics/accuracy_top1' : 'metrics/mAP50-95(B)')}"
  direction: "maximize"
`;
            } else {
                sweeperBlock = `
sweeper:
  trials: 1
  sampler: "tpe"
  metric: "${task === 'classify' ? 'metrics/accuracy_top1' : 'metrics/mAP50-95(B)'}"
  direction: "maximize"
`;
            }

            const queueBlock = targetQueue && targetQueue !== 'auto'
                ? `  target_worker_queue: "${targetQueue}"\n`
                : '';

            const yamlContent = `# =====================================================================
# NeuralForge Distributed Training Configuration
# Generated by NeuralForge Studio Hub
# Architecture: YOLO26 / v8 | Task: ${task}
# =====================================================================

study_name: "${sanitizedStudy}"
description: "${description || 'NeuralForge training run'}"
model: "${model}"
dataset: "${dataset}"
task: "${task}"

epochs: ${epochs || 100}
batch_size: ${batchSize || 32}
imgsz: 640

post_train:
  xai_enabled: ${xaiEnabled ? 'true' : 'false'}
  adversarial_test: false
  latex_export: true
  llm_report: true
${sweeperBlock}${queueBlock}`;

            try {
                fs.writeFileSync(configFilePath, yamlContent, 'utf-8');
            } catch (err: any) {
                panel.webview.postMessage({ command: 'error', message: `Failed to write YAML: ${err.message}` });
                return;
            }

            // Mode 1: Generate YAML only
            if (message.command === 'generateYamlOnly') {
                panel.webview.postMessage({
                    command: 'yamlGenerated',
                    filePath: configFilePath,
                    message: `✅ YAML configuration saved to ${configFileName}`
                });

                // Open file in active editor
                const doc = await vscode.workspace.openTextDocument(vscode.Uri.file(configFilePath));
                await vscode.window.showTextDocument(doc, { viewColumn: vscode.ViewColumn.Beside });
                vscode.window.showInformationMessage(`📄 Configuration opened: ${configFileName}. Use the CodeLens buttons on top to launch or preview.`);
                return;
            }

            // Mode 2: Submit to Cluster directly
            vscode.window.withProgress({
                location: vscode.ProgressLocation.Notification,
                title: `Submitting ${sanitizedStudy} to NeuralForge Cluster...`,
                cancellable: false
            }, async () => {
                const client = ClusterApiClient.getInstance();
                const res = await client.submitTraining(configFilePath, yamlContent, {
                    mode: targetQueue && targetQueue !== 'auto' ? 'private' : 'public',
                    workerName: targetQueue !== 'auto' ? targetQueue : undefined,
                    priority: targetQueue === 'gpus_high' ? 'high' : 'medium'
                });

                if (res.success && res.study_id) {
                    const studyId = res.study_id;

                    // Inject study_id at top of YAML
                    try {
                        const updated = `study_id: "${studyId}"\n` + yamlContent;
                        fs.writeFileSync(configFilePath, updated, 'utf-8');
                    } catch {}

                    panel.webview.postMessage({
                        command: 'submitted',
                        studyId,
                        message: `🚀 Training launched successfully! Registered Study ID: ${studyId}`
                    });

                    // Open the generated YAML with CodeLens active
                    const doc = await vscode.workspace.openTextDocument(vscode.Uri.file(configFilePath));
                    await vscode.window.showTextDocument(doc, { viewColumn: vscode.ViewColumn.Beside });

                    vscode.window.showInformationMessage(
                        `🚀 Training dispatched! Study ID: "${studyId}".`,
                        '📈 View Live Curves',
                        '📜 Tail Real-Time Logs'
                    ).then(action => {
                        if (action === '📈 View Live Curves') {
                            vscode.commands.executeCommand('neuralforge.viewMetricsCurves', studyId);
                        } else if (action === '📜 Tail Real-Time Logs') {
                            LogStreamer.getInstance().startStreaming(studyId);
                        }
                    });

                    // Refresh experiment views
                    vscode.commands.executeCommand('neuralforge.refreshAllViews');
                } else {
                    panel.webview.postMessage({
                        command: 'error',
                        message: res.error || 'Failed to submit training job to cluster.'
                    });
                }
            });
        }
    }, undefined, context.subscriptions);
}

