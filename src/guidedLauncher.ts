import * as vscode from 'vscode';
import * as fs from 'fs';
import * as path from 'path';
import { ClusterApiClient } from './clusterApiClient';
import { LogStreamer } from './logStreamer';

export function openGuidedLauncher(context: vscode.ExtensionContext) {
    const panel = vscode.window.createWebviewPanel(
        'neuralforgeGuidedLaunch',
        '🚀 NeuralForge: New Training Hub',
        vscode.ViewColumn.One,
        {
            enableScripts: true,
            retainContextWhenHidden: true
        }
    );

    panel.webview.html = getGuidedLauncherHtml();

    panel.webview.onDidReceiveMessage(async (message) => {
        if (message.command === 'submitTraining') {
            const { dataset, model, task, epochs, batchSize, xaiEnabled, targetNode } = message.payload;

            // Generate clean YAML configuration in workspace
            const workspaceFolders = vscode.workspace.workspaceFolders;
            const targetFolder = workspaceFolders && workspaceFolders.length > 0
                ? workspaceFolders[0].uri.fsPath
                : process.cwd();

            const studyName = `train_${model.replace('.pt', '')}_${Date.now().toString(36)}`;
            const configFileName = `neuralforge_${studyName}.yaml`;
            const configFilePath = path.join(targetFolder, configFileName);

            const yamlContent = `# NeuralForge Training Descriptor (Generated by Studio Hub)
study_name: "${studyName}"
model: "${model}"
dataset: "${dataset}"
task: "${task}"

epochs: ${epochs}
batch_size: ${batchSize}
imgsz: 640

post_train:
  xai_enabled: ${xaiEnabled ? 'true' : 'false'}
  adversarial_test: false
  latex_export: true
  llm_report: true

sweeper:
  trials: 1
  sampler: "tpe"
  metric: "metrics/mAP50-95(B)"
  direction: "maximize"
${targetNode ? `  target_worker_queue: "${targetNode}"` : ''}
`;

            try {
                fs.writeFileSync(configFilePath, yamlContent, 'utf-8');
            } catch (err: any) {
                panel.webview.postMessage({ command: 'error', message: `Failed to write YAML: ${err.message}` });
                return;
            }

            vscode.window.withProgress({
                location: vscode.ProgressLocation.Notification,
                title: `Submitting ${studyName} to NeuralForge Cluster...`,
                cancellable: false
            }, async () => {
                const client = ClusterApiClient.getInstance();
                const res = await client.submitTraining(configFilePath, yamlContent, {
                    mode: targetNode ? 'private' : 'public',
                    workerName: targetNode,
                    priority: 'medium'
                });

                if (res.success && res.study_id) {
                    const studyId = res.study_id;

                    // Update YAML with study_id
                    try {
                        const updated = `study_id: "${studyId}"\n` + yamlContent;
                        fs.writeFileSync(configFilePath, updated, 'utf-8');
                    } catch {}

                    panel.webview.postMessage({
                        command: 'submitted',
                        studyId,
                        message: `Training successfully launched! Study ID: ${studyId}`
                    });

                    vscode.window.showInformationMessage(
                        `🚀 Training dispatched! Study ID: "${studyId}".`,
                        '📜 Stream Live Logs',
                        '📈 View Metrics Curves'
                    ).then(action => {
                        if (action === '📜 Stream Live Logs') {
                            LogStreamer.getInstance().startStreaming(studyId);
                        } else if (action === '📈 View Metrics Curves') {
                            vscode.commands.executeCommand('neuralforge.viewMetricsCurves', studyId);
                        }
                    });

                    // Refresh experiment views
                    vscode.commands.executeCommand('neuralforge.refreshAllViews');
                } else {
                    panel.webview.postMessage({
                        command: 'error',
                        message: res.error || 'Failed to submit training job.'
                    });
                }
            });
        }
    }, undefined, context.subscriptions);
}

